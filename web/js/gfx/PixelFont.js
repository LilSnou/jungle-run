  static GLYPH_W = 5;
  static GLYPH_H = 7;
  static TRACKING = 1;

  /** Ширина строки в пикселях спрайта-сетки. */
  static measure(text, scale = 1) {
    const n = String(text).length;
    return n === 0 ? 0 : (n * (PixelFont.GLYPH_W + PixelFont.TRACKING) - PixelFont.TRACKING) * scale;
  }

  /**
   * Отрисовка строки.
   * @param {CanvasRenderingContext2D} ctx
   * @param {string} text
   * @param {number} x левый край
   * @param {number} y верхний край
   * @param {object} [opts] { scale, color, align: 'left'|'center'|'right', shadow }
   */
  static draw(ctx, text, x, y, opts = {}) {
    const scale = opts.scale || 1;
    const color = opts.color || '#f7f3e3';
    const align = opts.align || 'left';
    const str = String(text);
    const w = PixelFont.measure(str, scale);
    let px = align === 'center' ? Math.round(x - w / 2) : (align === 'right' ? Math.round(x - w) : Math.round(x));
    const py = Math.round(y);

    if (opts.shadow) {
      PixelFont.draw(ctx, str, px + scale, py + scale, { scale, color: opts.shadow });
    }

    ctx.fillStyle = color;
    for (const ch of str) {
      const glyph = PixelFont.DATA[ch] || PixelFont.DATA[ch.toUpperCase()] || PixelFont.DATA['?'];
      for (let r = 0; r < PixelFont.GLYPH_H; r++) {
        const row = glyph[r];
        let runStart = -1;
        for (let c = 0; c <= PixelFont.GLYPH_W; c++) {
          const on = c < PixelFont.GLYPH_W && row[c] === '1';
          if (on && runStart < 0) runStart = c;
          if (!on && runStart >= 0) {
            ctx.fillRect(px + runStart * scale, py + r * scale, (c - runStart) * scale, scale);
            runStart = -1;
          }
        }
      }
      px += (PixelFont.GLYPH_W + PixelFont.TRACKING) * scale;
    }
  }

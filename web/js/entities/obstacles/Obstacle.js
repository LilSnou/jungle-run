/**
 * Obstacle — абстрактный базовый класс препятствий.
 * Конкретные препятствия (шипы, бревно, статуя, яма) наследуют его
 * и переопределяют хитбокс и отрисовку (полиморфизм).
 */
class Obstacle extends Entity {
  constructor(x, y, w, h) { super(x, y, w, h); }

  get damageOnTouch() { return true; }
  get stompable() { return false; }

  /** Препятствие «над головой» (под ним нельзя вставать, пока не проедет). */
  get isOverhead() { return false; }

  /** Игрок врезался: препятствие может отреагировать (по умолчанию — молчит). */
  onHit(player) { /* реакция конкретного препятствия */ }

  /** Дымка «опасности» — маленькие частицы для атмосферы. */
  update(dt) { /* у большинства препятствий нет внутренней логики */ }
}
